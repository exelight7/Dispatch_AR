"""Build the context-sensitive literary review queue (highest risk first).

python -X utf8 tools/translation_qa/review_queue.py
Writes translation/review/review_queue.json and translation/review/REVIEW_QUEUE.md. Review state
(translation/review/review_log.json) is merged in so reviewed records keep their status.
"""
from __future__ import annotations

from collections import Counter, defaultdict
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).parent))
from qa import load_records  # noqa: E402

RULES = [  # (category, priority weight, predicate)
    ("legal_safety", 100, lambda r, c: re.search(r"Consent|Copyright|EULA|Privacy|Terms|License|rights reserved|personal information", r["en"] + c, re.I)),
    ("branching_choice", 90, lambda r, c: re.search(r"Choice|ChoiceUIs|Option|DialogueChoice|\.Choices", c) or re.fullmatch(r"\[.*\]", r["en"].strip())),
    ("tutorial_instruction", 85, lambda r, c: re.search(r"Tutorial|FTUE|QTE|Hint|Prompt", c + r["namespace"], re.I)),
    ("ui_action_or_setting", 80, lambda r, c: r["target"] == "Shared" and re.search(r"Menu|Setting|Save|Episode|Input|Button|Widget", c + r["namespace"])),
    ("system_message", 70, lambda r, c: r["target"] in ("EngineRuntime", "OnlineSubsystem", "OnlineSubsystemSteam", "OnlineSubsystemUtils")),
    ("ambiguous_short_ui", 65, lambda r, c: len(r["en"].split()) <= 2 and not r["speaker"] and r["en"] != r["ar"]),
    ("emotional_or_joke_dialogue", 50, lambda r, c: r["speaker"] and re.search(r"!\?|\?!|\.\.\.|--|fuck|shit|damn|haha|lol", r["en"], re.I)),
    ("speaker_dialogue", 40, lambda r, c: bool(r["speaker"])),
    ("other", 10, lambda r, c: True),
]


def main():
    rows = load_records()
    by_en = defaultdict(list)
    for r in rows:
        by_en[r["en"]].append(r)
    qa_path = ROOT / "reports/validation/translation_qa.json"
    qa_ids = Counter(f["id"] for f in json.loads(qa_path.read_text(encoding="utf-8"))["findings"]) if qa_path.exists() else Counter()
    log_path = ROOT / "translation/review/review_log.json"
    log = {e["id"]: e for e in json.loads(log_path.read_text(encoding="utf-8"))} if log_path.exists() else {}
    queue = []
    for r in rows:
        if r["ar"] == r["en"]:
            continue  # verbatim technical keeps are covered by VERBATIM_APPROVALS/is_technical
        context = " ".join(r["context"]) + " " + r["category"]
        cats = [name for name, _, pred in RULES if pred(r, context)]
        weight = max(w for name, w, _ in RULES if name in cats)
        dup = by_en[r["en"]]
        divergent = len(dup) > 1 and len({d["ar"] for d in dup}) > 1
        if divergent:
            cats.append("duplicate_english_divergent_arabic")
            weight += 15
        if qa_ids[r["id"]]:
            cats.append("qa_warning")
            weight += 10
        state = log.get(r["id"], {})
        queue.append({"id": r["id"], "target": r["target"], "index": r["index"], "priority": weight,
                      "categories": [c for c in cats if c != "other"] or ["other"], "speaker": r["speaker"],
                      "en": r["en"], "ar": r["ar"], "context": r["context"][:2],
                      "review_status": state.get("status", "UNREVIEWED"), "review_note": state.get("note", "")})
    queue.sort(key=lambda q: (-q["priority"], q["target"], q["index"]))
    out = ROOT / "translation/review"
    out.mkdir(parents=True, exist_ok=True)
    (out / "review_queue.json").write_text(json.dumps(queue, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    cat_counts = Counter(c for q in queue for c in q["categories"])
    status = Counter(q["review_status"] for q in queue)
    lines = ["# Literary review queue", "",
             "Generated by `python -X utf8 tools/translation_qa/review_queue.py`. Records are ordered by risk; "
             "automated QA is not review. Status values: UNREVIEWED, REVIEWED_OK, CHANGED_AFTER_REVIEW, NEEDS_CONTEXT, BLOCKED.", "",
             f"Queue size (Arabic-changed records): **{len(queue)}**", "", "## Review status", "",
             "| Status | Records |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(status.items())]
    lines += ["", "## Risk categories (a record can have several)", "", "| Category | Records |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in cat_counts.most_common()]
    lines += ["", "## Top 40 unreviewed", "", "| Priority | ID | Categories | English |", "|---:|---|---|---|"]
    for q in [q for q in queue if q["review_status"] == "UNREVIEWED"][:40]:
        en = q["en"].replace("|", "\\|").replace("\n", " ")[:80]
        lines.append(f"| {q['priority']} | `{q['id']}` | {', '.join(q['categories'])} | {en} |")
    (out / "REVIEW_QUEUE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"queue": len(queue), "status": dict(status), "categories": dict(cat_counts)}, indent=2))


if __name__ == "__main__":
    main()
